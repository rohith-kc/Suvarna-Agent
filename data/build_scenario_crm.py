"""Builds data/crm.sqlite from every scenario in data/scenarios.yaml
(CLAUDE.md Part 5.3a), not from a random bulk leads.jsonl.

For a deployed tools server (Phase 7): the docs/test_cards/ KC pastes into
ElevenLabs use scenario lead_ids like "scenario-uc2_busy", so the deployed
CRM needs exactly those rows, not whatever happened to be generated by the
last `python data/generate_leads.py` run. Run this as part of the deploy's
build step (see render.yaml) so the CRM is always fresh and matches every
test card.

Usage: python data/build_scenario_crm.py [--out data/crm.sqlite]
"""

import argparse
import hashlib
import os
import sys

if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import yaml

from data.build_crm import build_crm_from_leads
from data.generate_leads import build_lead_from_scenario

SCENARIOS_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "scenarios.yaml")


def _stable_seed(text):
    # Mirrors simulation/run_simulation.py's _stable_seed() so a given
    # scenario id always gets the same underlying random lead.
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return int(digest[:8], 16)


def build_scenario_crm(out_path):
    with open(SCENARIOS_PATH, "r", encoding="utf-8") as f:
        scenarios = yaml.safe_load(f)["scenarios"]

    leads = []
    for scenario in scenarios:
        record = build_lead_from_scenario(scenario, seed=_stable_seed(scenario["id"]))
        leads.append(record["lead"])

    build_crm_from_leads(leads, out_path)
    return len(leads)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="data/crm.sqlite")
    args = parser.parse_args()
    n = build_scenario_crm(args.out)
    print(f"Built CRM at {args.out} from {n} scenarios")


if __name__ == "__main__":
    main()
